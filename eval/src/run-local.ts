import { join } from "node:path";
import { measureAttackInjection } from "./measure-attack.js";
import { measureGraceWindow } from "./measure-grace.js";
import { measureHandshakeOverhead } from "./measure-handshake.js";
import { measureRevocationDelay } from "./measure-revocation-delay.js";
import { measureScaling } from "./measure-scaling.js";
import { measureVerifyCost } from "./measure-verify-cost.js";
import {
  appendMarkdown,
  ensureRunDirs,
  environmentInfo,
  parseArgs,
  readTextIfExists,
  round,
  writeJson
} from "./common.js";

interface MeasureResult {
  name: string;
  rows: readonly Record<string, unknown>[];
  ms: number;
}

async function main(): Promise<void> {
  const config = parseArgs();
  ensureRunDirs(config.outDir);
  writeJson(join(config.outDir, "environment.json"), {
    ...environmentInfo(),
    evalMode: config.mode,
    repeats: config.repeats,
    skipDocker: config.skipDocker,
    measures: Array.from(config.measures)
  });

  const results: MeasureResult[] = [];
  for (const measure of [
    ["scaling", measureScaling],
    ["revocation-delay", measureRevocationDelay],
    ["handshake", measureHandshakeOverhead],
    ["verify-cost", measureVerifyCost],
    ["grace", measureGraceWindow],
    ["attack", measureAttackInjection]
  ] as const) {
    const [name, fn] = measure;
    if (!config.measures.has(name)) {
      continue;
    }
    console.log(`[eval] ${name} started`);
    const started = Date.now();
    const rows = await fn(config) as readonly Record<string, unknown>[];
    const ms = Date.now() - started;
    results.push({ name, rows, ms });
    console.log(`[eval] ${name} completed in ${round(ms)}ms (${rows.length} rows)`);
  }

  writeReport(config.outDir, results);
  console.log(`[eval] output: ${config.outDir}`);
}

function writeReport(outDir: string, results: readonly MeasureResult[]): void {
  const lines: string[] = [
    "# VADREX 8A Local Evaluation Report",
    "",
    `Generated at: ${new Date().toISOString()}`,
    "",
    "## Measure Summary",
    "",
    "| Measure | Rows | Runtime ms | OK | Failed | Skipped |",
    "|---|---:|---:|---:|---:|---:|"
  ];
  for (const result of results) {
    const ok = result.rows.filter((row) => row.status === "ok" || row.status === "success").length;
    const failed = result.rows.filter((row) => row.status === "failed" || row.status === "failure").length;
    const skipped = result.rows.filter((row) => row.status === "skipped").length;
    lines.push(`| ${result.name} | ${result.rows.length} | ${round(result.ms)} | ${ok} | ${failed} | ${skipped} |`);
  }

  lines.push(
    "",
    "## Raw Outputs",
    "",
    "- `raw/scaling.csv` / `raw/scaling.json`",
    "- `raw/revocation_delay.csv` / `raw/revocation_delay.json`",
    "- `raw/handshake_overhead.csv` / `raw/handshake_overhead.json`",
    "- `raw/verify_cost.csv` / `raw/verify_cost.json`",
    "- `raw/grace_window.csv` / `raw/grace_window.json`",
    "- `raw/attack_injection.csv` / `raw/attack_injection.json`",
    "- `summary/*-numeric-summary.csv` for count/mean/stddev/median/min/max of core numeric metrics",
    "",
    "## Figures",
    "",
    "Generated by `eval/run-plots.ps1` from the CSVs above:",
    "",
    "- `figures/scaling.png`",
    "- `figures/revocation_delay.png`",
    "- `figures/handshake_overhead.png`",
    "- `figures/verify_cost.png`",
    "- `figures/grace_window.png`",
    "- `figures/attack_injection.png`",
    "",
    "## Notes",
    "",
    "- quick mode is for pipeline validation, not paper numbers.",
    "- 10^7 leaves are not run unless `EVAL_INCLUDE_10M=true` is explicitly set.",
    "- Gateway API bytes are measured by verifier-cli; JSON-RPC wire bytes are represented by RPC call counts.",
    ""
  );

  const tenMillionEstimate = readTextIfExists(join(outDir, "summary", "scaling-10m-estimate.json"));
  if (tenMillionEstimate) {
    const estimate = JSON.parse(tenMillionEstimate) as Record<string, unknown>;
    lines.push(
      "## 10^7 Leaf Execution Note",
      "",
      `- Included in this run: ${String(estimate.includedInRun)}`,
      `- Explicit opt-in: ${String(estimate.explicitOptIn)}`,
      `- Max measured leaves: ${String(estimate.maxMeasuredLeaves)}`,
      `- Estimated tree build ms: ${String(estimate.estimatedTreeBuildMs)}`,
      `- Note: ${String(estimate.note)}`,
      ""
    );
  }
  appendMarkdown(join(outDir, "summary", "report.md"), `${lines.join("\n")}\n`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
